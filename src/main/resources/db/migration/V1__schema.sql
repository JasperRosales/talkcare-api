CREATE TABLE conversations (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id       INTEGER  NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    professional_id INTEGER  NOT NULL REFERENCES professionals(user_id) ON DELETE RESTRICT,
    service_type_id SMALLINT NOT NULL REFERENCES service_types(service_type_id),
    title           VARCHAR(150),
    status          VARCHAR(20) NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN', 'CLOSED', 'ARCHIVED')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- One open conversation per client/service; old conversations remain as history.
CREATE UNIQUE INDEX conversations_one_open_per_service_uk
    ON conversations (client_id, service_type_id) WHERE status = 'OPEN';
CREATE INDEX conversations_professional_idx
    ON conversations (professional_id, status, updated_at DESC);

CREATE TABLE messages (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id INTEGER NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    -- NULL only for system auto-replies; every human message has a sender.
    sender_id       INTEGER REFERENCES users(id) ON DELETE RESTRICT,
    message_text    TEXT,
    is_auto_reply   BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT messages_sender_presence CHECK (
        (is_auto_reply AND sender_id IS NULL)
        OR (NOT is_auto_reply AND sender_id IS NOT NULL)
    )
);

CREATE INDEX messages_conversation_idx ON messages (conversation_id, created_at);
CREATE INDEX messages_sender_idx       ON messages (sender_id, created_at DESC);

CREATE TABLE message_attachments (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id INTEGER NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    file_url   TEXT NOT NULL,
    mime_type  VARCHAR(100),
    byte_size  BIGINT CHECK (byte_size >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX message_attachments_message_idx ON message_attachments (message_id);

